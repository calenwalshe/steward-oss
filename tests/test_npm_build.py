"""The allowlist build (G1, G2, G17): dist/npm holds exactly the allowlisted files with one stamped version."""

from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
import tomllib
from pathlib import Path

import pytest

from npm_helpers import REPO, build_dist, copy_repo, load_module, pyproject_version

FORBIDDEN_TOP = ("tests", "deploy", "docs", "spikes", "scripts", ".planning", "packaging", "dist")


def _files(root: Path) -> list[str]:
    return sorted(p.relative_to(root).as_posix() for p in root.rglob("*") if p.is_file())


def test_build_copies_only_the_allowlist(tmp_path):
    repo = copy_repo(tmp_path)
    (repo / "steward" / "notes.json").write_text("{}")
    (repo / "steward" / "x.db").write_text("")
    (repo / "steward" / "secret.env").write_text("")
    (repo / "steward" / "__pycache__").mkdir()
    (repo / "steward" / "__pycache__" / "m.cpython-312.pyc").write_bytes(b"\0")
    (repo / "steward" / "templates" / ".DS_Store").write_text("")
    dist = build_dist(tmp_path, repo)
    files = _files(dist)
    fixed = {"package.json", "README.md", "LICENSE", "herdr-plugin.toml", "bin/steward.js", "steward/_version.py"}
    assert fixed <= set(files)
    for rel in files:
        if rel in fixed:
            continue
        assert rel.startswith("steward/"), rel
        if rel.startswith("steward/templates/"):
            assert not os.path.basename(rel).startswith("."), rel
            continue
        assert rel.endswith(".py"), rel
    assert not [f for f in files if "__pycache__" in f or f.endswith((".pyc", ".db", ".env"))]
    assert "steward/notes.json" not in files and "steward/x.db" not in files
    assert not [f for f in files if f.split("/")[0] in FORBIDDEN_TOP]
    # every real template ships
    templates = sorted(p.relative_to(REPO).as_posix() for p in (REPO / "steward" / "templates").rglob("*")
                       if p.is_file() and "__pycache__" not in p.parts)
    assert set(templates) <= set(files)


def test_collect_is_sorted_and_explicit(tmp_path):
    build = load_module("steward_pack_build")
    pairs = build.collect(REPO)
    dests = [d for _, d in pairs]
    assert dests == sorted(dests)
    assert len(dests) == len(set(dests))
    assert "steward/_version.py" not in dests  # generated by the stamp, never copied
    assert all(s.is_file() for s, _ in pairs)


def test_version_is_stamped_everywhere(tmp_path):
    cfg = load_module("pack_config")
    dist = build_dist(tmp_path)
    ver = pyproject_version()
    pkg = json.loads((dist / "package.json").read_text())
    assert pkg["version"] == ver
    stamp = (dist / "steward" / "_version.py").read_text()
    assert re.search(rf'^VERSION = "{re.escape(ver)}"$', stamp, re.M)
    assert re.search(rf'^__version__ = "{re.escape(ver)}"$', stamp, re.M)
    assert tomllib.loads((dist / "herdr-plugin.toml").read_text())["version"] == ver
    npm_name = re.search(r'^NPM_PACKAGE = "([^"]+)"$', stamp, re.M).group(1)
    assert npm_name == pkg["name"] == cfg.FULL_NAME == f"{cfg.PACKAGE_SCOPE}/{cfg.PACKAGE_NAME}"
    assert cfg.PACKAGE_NAME == "steward"
    code = "import steward.version as v; print(v.version()); print(v.npm_package())"
    out = subprocess.run([sys.executable, "-P", "-c", code], cwd=tmp_path, capture_output=True, text=True,
                         env={**os.environ, "PYTHONPATH": str(dist), "PYTHONDONTWRITEBYTECODE": "1",
                              "STEWARD_INSTALL_ROOT": str(dist)})
    assert out.returncode == 0, out.stderr
    assert out.stdout.split() == [ver, cfg.FULL_NAME]


def test_build_is_deterministic(tmp_path):
    (tmp_path / "a").mkdir()
    (tmp_path / "b").mkdir()
    a = build_dist(tmp_path / "a")
    b = build_dist(tmp_path / "b")

    def digest(root):
        return {f: hashlib.sha256((root / f).read_bytes()).hexdigest() for f in _files(root)}

    assert digest(a) == digest(b)
    for f in _files(a):
        mode = (a / f).stat().st_mode & 0o777
        assert mode == (0o755 if f == "bin/steward.js" else 0o644), f


def test_build_cleans_the_output_dir_first(tmp_path):
    repo = copy_repo(tmp_path)
    build = load_module("steward_pack_build", repo)
    out = tmp_path / "dist" / "npm"
    out.mkdir(parents=True)
    (out / "stale.txt").write_text("x")
    build.build(out, repo_root=repo)
    assert not (out / "stale.txt").exists()


def test_build_refuses_to_clean_the_repo_or_an_ancestor(tmp_path):
    repo = copy_repo(tmp_path)
    build = load_module("steward_pack_build", repo)
    for bad in (repo, repo.parent, Path.home()):
        with pytest.raises(ValueError):
            build.build(bad, repo_root=repo)
    assert (repo / "steward").is_dir()


def test_pack_config_is_not_the_owner():
    cfg = load_module("pack_config")
    assert not re.search(r"sam(?!dar)", cfg.PACKAGE_SCOPE, re.I)
    assert cfg.PACKAGE_SCOPE.startswith("@")
    assert cfg.FULL_NAME == "@steward-local/steward"


def test_no_init_py_under_packaging():
    assert not list((REPO / "packaging").rglob("__init__.py"))


def test_cli_main_builds_into_out(tmp_path):
    build = load_module("steward_pack_build")
    out = tmp_path / "o"
    assert build.main(["--out", str(out)]) == 0
    assert (out / "bin" / "steward.js").is_file()
